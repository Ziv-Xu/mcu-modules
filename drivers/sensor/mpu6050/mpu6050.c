/**
 * @brief 向 DMP 存储区写入数据
 * @param hmpu 设备句柄
 * @param mem_addr 起始地址 (16位)
 * @param data 数据指针
 * @param length 数据长度
 * @return 错误码
 */
static MPU6050_Status MPU6050_DMP_WriteMem(MPU6050_HandleTypeDef *hmpu, uint16_t mem_addr, const uint8_t *data,
                                           uint16_t length)
{
    if (hmpu == NULL || data == NULL || length == 0U)
    {
        return MPU6050_ERR_INVALID_PARAM;
    }

    while (length > 0U)
    {
        uint8_t  bank     = (uint8_t) ((mem_addr >> 8) & 0x1FU);
        uint8_t  addr_low = (uint8_t) (mem_addr & 0xFFU);
        uint16_t chunk    = (uint16_t) (256U - (uint16_t) addr_low);
        if (chunk > length)
        {
            chunk = length;
        }

        /* 设置 bank */
        MPU6050_Status status = WriteReg(hmpu, MPU6050_REG_BANK_SEL, bank);
        if (status != MPU6050_OK)
            return status;

        /* 设置起始地址 (高字节, 低字节) */
        uint8_t addr_buf[2] = {(uint8_t) (mem_addr >> 8), addr_low};
        if (hmpu->I2C_Write(hmpu->DeviceAddr, MPU6050_REG_MEM_START_ADDR, addr_buf, 2U) != 0)
        {
            return MPU6050_ERR_I2C;
        }

        /* 写入数据块 */
        if (hmpu->I2C_Write(hmpu->DeviceAddr, MPU6050_REG_MEM_R_W, data, (uint8_t) chunk) != 0)
        {
            return MPU6050_ERR_I2C;
        }

        mem_addr += chunk;
        data += chunk;
        length -= chunk;
    }

    return MPU6050_OK;
}

/**
 * @brief 加载 DMP 固件
 * @param hmpu 设备句柄
 * @return 错误码
 */
static MPU6050_Status MPU6050_DMP_LoadFirmware(MPU6050_HandleTypeDef *hmpu)
{
    if (hmpu == NULL)
        return MPU6050_ERR_INVALID_PARAM;

    /* 固件起始地址固定为 0x0400 */
    return MPU6050_DMP_WriteMem(hmpu, 0x0400U, dmp_firmware, (uint16_t) sizeof(dmp_firmware));
}

